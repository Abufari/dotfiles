  -- == Custom Plugins ==

  -- blink.cmp provides signature help itself; AstroLSP's own `features.signature_help`
  -- defaults to false, so this is what actually turns it on.
  {
    "Saghen/blink.cmp",
    opts = { signature = { enabled = true } },
  },

  -- == Examples of Overriding Plugins ==

  -- customize dashboard options
  {
    "folke/snacks.nvim",
    opts = {
